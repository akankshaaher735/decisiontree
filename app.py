@app.route("/predict", methods=["POST"])
def predict():
    try:
        payload = request.get_json(silent=True)
        if not isinstance(payload, dict):
            return jsonify({"success": False, "error": "Invalid JSON payload."}), 400

        X = build_feature_vector(payload)
        raw_pred = MODEL.predict(X)[0]
        pred_label = int(raw_pred) if isinstance(raw_pred, (np.integer, int)) else raw_pred
        pred_key = str(pred_label)

        probabilities_data = None
        confidence = None

        if hasattr(MODEL, "predict_proba"):
            probs = MODEL.predict_proba(X)[0]
            probabilities_data = [
                {
                    "class": int(c) if isinstance(c, (np.integer, int)) else c,
                    "probability": float(p),
                }
                for c, p in zip(CLASSES, probs)
            ]
            confidence = float(np.max(probs))

        CLASS_COUNTS[pred_key] = CLASS_COUNTS.get(pred_key, 0) + 1
        timestamp = datetime.now().strftime("%H:%M:%S")
        summary = ", ".join(f"{k}={payload[k]}" for k in FEATURE_ORDER[:4]) + ", ..."

        entry = {
            "timestamp": timestamp,
            "prediction": pred_label,
            "confidence": confidence,
            "summary": summary,
            "inputs": {k: payload[k] for k in FEATURE_ORDER},
        }
        SESSION_HISTORY.append(entry)

        return jsonify(
            {
                "success": True,
                "prediction": pred_label,
                "confidence": confidence,
                "probabilities": probabilities_data,
                "total_predictions": len(SESSION_HISTORY),
                "class_counts": CLASS_COUNTS,
                "entry": entry,
            }
        )
    except ValueError as exc:
        return jsonify({"success": False, "error": str(exc)}), 400
    except Exception as exc:
        return jsonify({"success": False, "error": f"Inference error: {exc}"}), 500


@app.route("/clear-history", methods=["POST"])
def clear_history():
    SESSION_HISTORY.clear()
    for key in CLASS_COUNTS:
        CLASS_COUNTS[key] = 0
    return jsonify({"success": True})


@app.route("/download-csv", methods=["GET"])
def download_csv():
    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow(["timestamp", "predicted_class", "confidence", *FEATURE_ORDER])
    for row in SESSION_HISTORY:
        inputs = row.get("inputs", {})
        writer.writerow(
            [
                row.get("timestamp", ""),
                row.get("prediction", ""),
                f"{row['confidence']:.6f}" if row.get("confidence") is not None else "",
                *[inputs.get(feat, "") for feat in FEATURE_ORDER],
            ]
        )
    return Response(
        output.getvalue(),
        mimetype="text/csv",
        headers={"Content-Disposition": "attachment; filename=predictions_history.csv"},
    )


